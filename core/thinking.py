"""Proactive thinking engine for Jarvis.

This module implements the proactive thinking system that allows Jarvis to
think on behalf of the user, anticipate needs, and offer curated insights
at natural conversation pauses.

Key features:
- Multiple thinking modes (supportive, analytical, creative)
- Confidence-based suggestion filtering
- Pause detection for natural timing
- Background thinking loop
"""
import asyncio
import logging
import re
import time
from dataclasses import dataclass, field
from datetime import datetime
from enum import Enum
from typing import Any, Callable

from core.helpers import get_response_content, create_tracked_task, read_json_with_integrity
from .prompts import PromptManager

logger = logging.getLogger(__name__)


class ThinkingMode(Enum):
    """Modes for proactive thinking."""
    SUPPORTIVE = "supportive"
    ANALYTICAL = "analytical"
    CREATIVE = "creative"


class SuggestionType(Enum):
    """Types of proactive suggestions."""
    INSIGHT = "insight"           # "I noticed something interesting..."
    QUESTION = "question"         # "Have you considered..."
    CONNECTION = "connection"     # "This reminds me of..."
    ENCOURAGEMENT = "encouragement"  # "Your thinking on X was really insightful..."
    ALTERNATIVE = "alternative"   # "Another angle to consider..."
    REMINDER = "reminder"         # "You mentioned wanting to..."


@dataclass
class Thought:
    """Represents a proactive thought generated by the thinking engine."""
    content: str
    suggestion_type: SuggestionType
    confidence: float  # 0.0 to 1.0
    reasoning: str = ""
    timestamp: datetime = field(default_factory=datetime.now)
    topics: list[str] = field(default_factory=list)
    should_display: bool = True

    def to_dict(self) -> dict[str, Any]:
        """Convert thought to dictionary for serialization."""
        return {
            "content": self.content,
            "suggestion_type": self.suggestion_type.value,
            "confidence": self.confidence,
            "reasoning": self.reasoning,
            "timestamp": self.timestamp.isoformat(),
            "topics": self.topics,
            "should_display": self.should_display,
        }


@dataclass
class ConversationContext:
    """Context for proactive thinking."""
    recent_messages: list[dict[str, str]] = field(default_factory=list)
    topics: list[str] = field(default_factory=list)
    user_goals: list[str] = field(default_factory=list)
    time_since_last_message: float = 0.0
    conversation_turns: int = 0
    important_entities: dict[str, Any] = field(default_factory=dict)


class ThinkingEngine:
    """Proactive thinking engine for Jarvis.

    This engine runs in the background and generates proactive thoughts
    based on conversation context. It uses confidence thresholds to
    determine which thoughts should be displayed to the user.

    Example usage:
        engine = ThinkingEngine(llm_client, config)
        await engine.start()

        # Engine runs in background, calling suggestion_callback when appropriate
        # When done:
        await engine.stop()
    """

    def __init__(
        self,
        llm_client: Any,
        config: Any,
        suggestion_callback: Callable[[Thought], None] | None = None,
    ):
        """Initialize the thinking engine.

        Args:
            llm_client: The LLM client for generating thoughts
            config: Configuration object with thinking settings
            suggestion_callback: Optional callback for when a suggestion is ready
        """
        self.llm = llm_client
        self.config = config
        self.suggestion_callback = suggestion_callback

        self._api_manager = None
        self._subsystem_name = "thinking"

        # Thinking state
        self.enabled = getattr(config.thinking, 'enabled', True)
        self.mode = getattr(config.thinking, 'mode', 'supportive')
        self.suggestion_interval = getattr(config.thinking, 'suggestion_interval', 30)
        self.confidence_threshold = getattr(config.thinking, 'confidence_threshold', 0.7)
        self.max_suggestions_per_turn = getattr(config.thinking, 'max_suggestions_per_turn', 3)
        self.pause_detection = getattr(config.thinking, 'pause_detection', True)

        # Pause detection settings
        self.pause_threshold = 5.0  # seconds of silence to consider a pause
        self.last_user_message_time: float | None = None
        self.last_suggestion_time: float = 0.0
        self.suggestions_this_turn = 0

        # Conversation tracking
        self.context = ConversationContext()
        self.prompt_manager = PromptManager(
            name=getattr(config.identity, 'name', 'Jarvis'),
            mode=self.mode,
        )

        # Background task
        self._running = False
        self._task: asyncio.Task | None = None

        # Persistent state and confidence learning
        self._state_path = None
        self._confidence_history: dict[str, list[float]] = {}
        self._MAX_CONFIDENCE_HISTORY = 100
        self._suggestion_outcomes: dict[str, str] = {}
        self._MAX_OUTCOMES = 200
        self._total_suggestions = 0
        self._accepted_suggestions = 0
        self._last_outcome_save = 0

        # Load persistent state
        self._load_state()

    def _get_api_manager(self):
        """Get or create API manager for coordinated LLM calls."""
        if self._api_manager is None and self.llm:
            try:
                from core.api_manager import get_api_manager
                self._api_manager = get_api_manager(self.llm)
            except Exception as e:
                logger.debug(f"Failed to get API manager for thinking: {e}")
        return self._api_manager

    async def _llm_call(self, user_input: str, system_prompt: str, priority: str = "learning") -> dict:
        """Make coordinated LLM call with rate limiting."""
        from core.api_manager import Priority as APIPriority

        priority_map = {
            "interactive": APIPriority.INTERACTIVE,
            "learning": APIPriority.LEARNING,
            "daydream": APIPriority.DAYDREAM,
        }

        api_manager = self._get_api_manager()
        if api_manager is not None:
            return await api_manager.submit_chat(
                subsystem=self._subsystem_name,
                priority=priority_map.get(priority, APIPriority.LEARNING),
                user_input=user_input,
                system_prompt=system_prompt,
            )

        if self.llm:
            return await self.llm.chat(user_input=user_input, system_prompt=system_prompt)

        raise RuntimeError("No LLM client available")

    async def start(self) -> None:
        """Start the background thinking loop."""
        if not self.enabled:
            return

        self._running = True
        self._task = create_tracked_task(self._run_background_loop(), name="thinking_background_loop")

    async def stop(self) -> None:
        """Stop the background thinking loop."""
        self._running = False
        if self._task:
            self._task.cancel()
            try:
                await self._task
            except asyncio.CancelledError:
                pass
            self._task = None

    async def _run_background_loop(self) -> None:
        """Background loop that periodically thinks proactively."""
        while self._running:
            try:
                # Wait for the suggestion interval
                await asyncio.sleep(self.suggestion_interval)

                # Check if we should generate a thought
                if await self._should_think():
                    thought = await self.think(self.context)

                    if thought and await self.should_suggest(thought):
                        if self.suggestion_callback:
                            self.suggestion_callback(thought)

            except asyncio.CancelledError:
                logger.debug("Thinking engine cancelled")
                break
            except Exception as e:
                logger.error(f"Thinking engine error: {e}")
                await asyncio.sleep(10)  # Brief pause before retry

    async def _should_think(self) -> bool:
        """Determine if we should generate a proactive thought.

        Integrates Thought Sense cognitive state for adaptive timing:
        - Suppresses suggestions during FLOW state (do not disturb)
        - Increases interval during OVERLOADED state
        - Reduces interval during ENGAGED/EXPLORING states
        
        Returns:
            True if conditions are right for proactive thinking
        """
        if not self.enabled:
            return False

        if not self.context.recent_messages:
            return False

        if self.suggestions_this_turn >= self.max_suggestions_per_turn:
            return False

        # Thought Sense integration: check cognitive state
        try:
            from core.thought_sense import get_thought_sense, CognitiveState
            thought_sense = get_thought_sense()
            ts_state = thought_sense.get_state()
            
            if ts_state.cognitive_state == CognitiveState.FLOW:
                # Do not disturb during flow state
                return False
            
            if ts_state.cognitive_state == CognitiveState.OVERLOADED:
                # Increase interval for overloaded users
                time_since_suggestion = time.time() - self.last_suggestion_time
                if time_since_suggestion < self.suggestion_interval * 3:
                    return False
        except Exception as e:
            logger.debug(f"Thought Sense check in _should_think failed: {e}")

        # Check for pause detection
        if self.pause_detection and self.last_user_message_time:
            time_since_last = time.time() - self.last_user_message_time
            if time_since_last < self.pause_threshold:
                return False

        # Don't suggest too frequently
        time_since_suggestion = time.time() - self.last_suggestion_time
        if time_since_suggestion < self.suggestion_interval:
            return False

        return True

    async def think(self, context: ConversationContext) -> Thought | None:
        """Generate a proactive thought based on context.

        Args:
            context: The conversation context to think about

        Returns:
            A Thought object if a valuable insight was generated, None otherwise
        """
        try:
            # Build the thinking prompt
            prompt = self.prompt_manager.get_suggestion_prompt({
                "recent_messages": context.recent_messages,
                "topics": context.topics,
                "user_goals": context.user_goals,
                "time_since_last_message": context.time_since_last_message,
            })

            # Use coordinated LLM call for rate limiting
            result = await self._llm_call(
                user_input=prompt,
                system_prompt="You are a thoughtful assistant providing helpful insights.",
                priority="learning",
            )

            content = get_response_content(result).strip()

            # Check for explicit "no suggestion" responses (more specific patterns)
            no_suggestion_patterns = [
                "no suggestion available",
                "i have no suggestion",
                "no relevant suggestion",
                "nothing to suggest",
            ]
            if any(p in content.lower() for p in no_suggestion_patterns) or len(content) < 10:
                return None

            # Parse the thought
            thought = self._parse_thought(content, context)

            return thought

        except Exception as e:
            logger.error(f"Error generating thought: {e}")
            return None

    def _parse_thought(self, content: str, context: ConversationContext) -> Thought:
        """Parse LLM response into a Thought object.

        Args:
            content: The raw LLM response
            context: The conversation context

        Returns:
            A Thought object
        """
        # Determine suggestion type based on content
        suggestion_type = self._classify_suggestion(content)

        # Estimate confidence based on content quality indicators
        confidence = self._estimate_confidence(content, suggestion_type=suggestion_type.value)

        return Thought(
            content=content,
            suggestion_type=suggestion_type,
            confidence=confidence,
            topics=context.topics.copy(),
        )

    def _classify_suggestion(self, content: str) -> SuggestionType:
        """Classify the type of suggestion based on content.

        Args:
            content: The suggestion content

        Returns:
            The classified SuggestionType
        """
        content_lower = content.lower()

        if any(phrase in content_lower for phrase in ["i noticed", "interesting", "pattern"]):
            return SuggestionType.INSIGHT

        if any(phrase in content_lower for phrase in ["have you considered", "what if", "might want to"]):
            return SuggestionType.QUESTION

        if any(phrase in content_lower for phrase in ["reminds me", "connects to", "similar to", "building on"]):
            return SuggestionType.CONNECTION

        if any(phrase in content_lower for phrase in ["great", "insightful", "well done", "excellent"]):
            return SuggestionType.ENCOURAGEMENT

        if any(phrase in content_lower for phrase in ["another angle", "alternative", "different approach"]):
            return SuggestionType.ALTERNATIVE

        if any(phrase in content_lower for phrase in ["you mentioned", "earlier you said", "reminder"]):
            return SuggestionType.REMINDER

        return SuggestionType.INSIGHT

    def _estimate_confidence(self, content: str, suggestion_type: str = "") -> float:
        """Estimate confidence score for a suggestion.

        Combines heuristic analysis with learned confidence from past outcomes.

        Args:
            content: The suggestion content
            suggestion_type: The type of suggestion for confidence calibration

        Returns:
            Confidence score between 0.0 and 1.0
        """
        confidence = 0.5  # Base confidence

        # Length indicates thoughtfulness
        if len(content) > 100:
            confidence += 0.1
        if len(content) > 200:
            confidence += 0.1

        # Contains specific references
        if any(word in content.lower() for word in ["specifically", "exactly", "particularly"]):
            confidence += 0.1

        # Contains hedging (reduces confidence slightly - but that's okay)
        if any(word in content.lower() for word in ["might", "perhaps", "possibly"]):
            confidence -= 0.05

        # Contains actionable suggestion
        if any(word in content.lower() for word in ["try", "consider", "could"]):
            confidence += 0.1

        # Learn from past outcomes: adjust confidence based on acceptance rate for this type
        if suggestion_type and suggestion_type in self._suggestion_outcomes:
            outcomes = [
                v for k, v in self._suggestion_outcomes.items()
                if k.startswith(suggestion_type + "_")
            ]
            if outcomes:
                acceptance_rate = outcomes.count("accepted") / len(outcomes)
                if acceptance_rate > 0.6:
                    confidence += 0.1
                elif acceptance_rate < 0.3:
                    confidence -= 0.15

        # Clamp to valid range
        return max(0.0, min(1.0, confidence))

    async def should_suggest(self, thought: Thought) -> bool:
        """Determine if a thought should be suggested to the user.

        Uses confidence threshold, relevance filtering, and Thought Sense
        cognitive state to ensure only high-quality, well-timed suggestions
        are shown.

        Args:
            thought: The thought to evaluate

        Returns:
            True if the thought should be suggested
        """
        # Check confidence threshold (modified by evolution genes if available)
        threshold = self.confidence_threshold
        try:
            from core.evolution_orchestrator import get_evolution_orchestrator
            orchestrator = get_evolution_orchestrator()
            if orchestrator and hasattr(orchestrator, 'get_behavior_params'):
                params = orchestrator.get_behavior_params()
                threshold = params.get("suggestion_threshold", threshold)
        except Exception as e:
            logger.debug(f"Failed to get evolution behavior params for threshold: {e}")

        if thought.confidence < threshold:
            return False

        if not thought.should_display:
            return False
        
        # Thought Sense integration: adapt confidence threshold by cognitive load
        try:
            from core.thought_sense import get_thought_sense
            thought_sense = get_thought_sense()
            should, _ = thought_sense.should_proactive_suggest()
            if not should:
                return False
        except Exception as e:
            logger.debug(f"Thought Sense check in should_suggest failed: {e}")

        return True

    def update_context(
        self,
        message: dict[str, str] | None = None,
        topics: list[str] | None = None,
        goals: list[str] | None = None,
    ) -> None:
        """Update the conversation context.

        Args:
            message: A new message to add to context
            topics: Updated list of topics
            goals: Updated list of user goals
        """
        if message:
            self.context.recent_messages.append(message)

            # Keep only recent messages
            max_context_messages = 20
            if len(self.context.recent_messages) > max_context_messages:
                self.context.recent_messages = self.context.recent_messages[-max_context_messages:]

            # Update last user message time if it's a user message
            if message.get("role") == "user":
                self.last_user_message_time = time.time()
                self.suggestions_this_turn = 0  # Reset for new turn

        if topics is not None:
            self.context.topics = topics

        if goals is not None:
            self.context.user_goals = goals

    def record_suggestion_shown(self, thought: Thought | None = None) -> None:
        """Record that a suggestion was shown to the user."""
        self.last_suggestion_time = time.time()
        self.suggestions_this_turn += 1
        self._total_suggestions += 1

        if thought and thought.suggestion_type:
            stype = thought.suggestion_type.value
            if stype not in self._confidence_history:
                self._confidence_history[stype] = []
            self._confidence_history[stype].append(thought.confidence)
            if len(self._confidence_history[stype]) > self._MAX_CONFIDENCE_HISTORY:
                self._confidence_history[stype] = self._confidence_history[stype][-self._MAX_CONFIDENCE_HISTORY:]
            # Cap total keys to prevent unbounded growth
            if len(self._confidence_history) > 20:
                for k in list(self._confidence_history.keys())[:len(self._confidence_history) - 20]:
                    del self._confidence_history[k]

    def reset_turn(self) -> None:
        """Reset the turn counter (call when user sends a new message)."""
        self.suggestions_this_turn = 0

    def set_mode(self, mode: str) -> bool:
        """Set the thinking mode.

        Args:
            mode: One of 'supportive', 'analytical', 'creative'

        Returns:
            True if mode was set successfully
        """
        if self.prompt_manager.set_mode(mode):
            self.mode = mode
            return True
        return False

    def get_status(self) -> dict[str, Any]:
        """Get the current status of the thinking engine.

        Returns:
            Dictionary with engine status information
        """
        return {
            "enabled": self.enabled,
            "running": self._running,
            "mode": self.mode,
            "confidence_threshold": self.confidence_threshold,
            "suggestions_this_turn": self.suggestions_this_turn,
            "recent_topics": self.context.topics,
            "last_user_message": self.last_user_message_time,
            "total_suggestions": self._total_suggestions,
            "accepted_suggestions": self._accepted_suggestions,
            "acceptance_rate": self._accepted_suggestions / max(self._total_suggestions, 1),
        }

    def record_suggestion_outcome(self, thought_id: str, accepted: bool) -> None:
        """Record whether a suggestion was accepted or dismissed.

        This enables confidence calibration — suggestion types that are
        frequently accepted get boosted confidence, while dismissed ones
        get reduced confidence.
        """
        outcome = "accepted" if accepted else "dismissed"
        self._suggestion_outcomes[thought_id] = outcome
        if len(self._suggestion_outcomes) > self._MAX_OUTCOMES:
            oldest_keys = list(self._suggestion_outcomes.keys())[:len(self._suggestion_outcomes) - self._MAX_OUTCOMES]
            for k in oldest_keys:
                del self._suggestion_outcomes[k]

        if accepted:
            self._accepted_suggestions += 1

        # Save state periodically (every 10 outcomes)
        self._last_outcome_save += 1
        if self._last_outcome_save >= 10:
            self._last_outcome_save = 0
            self._save_state()

    def get_adapted_confidence_threshold(self) -> float:
        """Adjust confidence threshold based on acceptance rate.

        If suggestions are frequently accepted, lower the threshold (show more).
        If frequently dismissed, raise the threshold (show fewer).
        """
        if self._total_suggestions < 10:
            return self.confidence_threshold

        acceptance_rate = self._accepted_suggestions / max(self._total_suggestions, 1)

        if acceptance_rate > 0.6:
            return max(0.3, self.confidence_threshold - 0.1)
        if acceptance_rate < 0.3:
            return min(0.9, self.confidence_threshold + 0.1)

        return self.confidence_threshold

    def _get_state_path(self):
        """Get the path for persistent state."""
        from pathlib import Path
        if self._state_path is None:
            self._state_path = Path.home() / ".jarvis" / "thinking_state.json"
        return self._state_path

    def _load_state(self):
        """Load persistent state from disk."""
        path = self._get_state_path()
        if not path.exists():
            return

        try:
            data = read_json_with_integrity(path)
            self._total_suggestions = data.get("total_suggestions", 0)
            self._accepted_suggestions = data.get("accepted_suggestions", 0)
            self._suggestion_outcomes = data.get("suggestion_outcomes", {})
            if len(self._suggestion_outcomes) > self._MAX_OUTCOMES:
                self._suggestion_outcomes = dict(
                    list(self._suggestion_outcomes.items())[-self._MAX_OUTCOMES:]
                )
            self._confidence_history = data.get("confidence_history", {})
            for key in self._confidence_history:
                if len(self._confidence_history[key]) > self._MAX_CONFIDENCE_HISTORY:
                    self._confidence_history[key] = self._confidence_history[key][-self._MAX_CONFIDENCE_HISTORY:]
            logger.debug(f"Loaded thinking state: {self._total_suggestions} suggestions, {self._accepted_suggestions} accepted")
        except Exception as e:
            logger.warning(f"Failed to load thinking state: {e}")

    def _save_state(self):
        """Save persistent state to disk."""
        from core.helpers import atomic_write_json
        path = self._get_state_path()
        try:
            data = {
                "total_suggestions": self._total_suggestions,
                "accepted_suggestions": self._accepted_suggestions,
                "suggestion_outcomes": dict(list(self._suggestion_outcomes.items())[-self._MAX_OUTCOMES:]),
                "confidence_history": {
                    k: v[-self._MAX_CONFIDENCE_HISTORY:]
                    for k, v in self._confidence_history.items()
                },
            }
            atomic_write_json(path, data)
        except Exception as e:
            logger.warning(f"Failed to save thinking state: {e}")


class TopicTracker:
    """Tracks topics discussed in conversation for the thinking engine."""

    def __init__(self):
        self.topics: dict[str, int] = {}  # topic -> frequency
        self.max_topics = 50

    def extract_topics(self, message: str) -> list[str]:
        """Extract topics from a message.

        This is a simple implementation. Could be enhanced with NER or
        topic modeling.

        Args:
            message: The message to extract topics from

        Returns:
            List of extracted topics
        """
        # Simple keyword extraction (could be enhanced)
        # For now, just track noun phrases and important terms

        # Extract capitalized phrases (likely entities)
        entities = re.findall(r'\b[A-Z][a-z]+(?:\s+[A-Z][a-z]+)*\b', message)

        # Extract quoted terms
        quoted = re.findall(r'"([^"]+)"', message)

        # Combine
        topics = list(set(entities + quoted))

        return [t for t in topics if len(t) > 2]

    def update(self, message: str) -> list[str]:
        """Update topics with a new message.

        Args:
            message: The new message

        Returns:
            Current top topics
        """
        new_topics = self.extract_topics(message)

        for topic in new_topics:
            self.topics[topic] = self.topics.get(topic, 0) + 1

        # Prune old topics if too many
        if len(self.topics) > self.max_topics:
            sorted_topics = sorted(self.topics.items(), key=lambda x: x[1], reverse=True)
            self.topics = dict(sorted_topics[:self.max_topics])

        return self.get_top_topics()

    def get_top_topics(self, n: int = 10) -> list[str]:
        """Get the top N most frequent topics.

        Args:
            n: Number of topics to return

        Returns:
            List of top topics
        """
        sorted_topics = sorted(self.topics.items(), key=lambda x: x[1], reverse=True)
        return [t[0] for t in sorted_topics[:n]]

    def clear(self) -> None:
        """Clear all tracked topics."""
        self.topics.clear()
