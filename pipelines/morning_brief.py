"""
Morning brief: per-user-per-day briefing assembled from the previous
24 hours. The chat UI reads this on first message of the day.

Content:
  * Top standing-order briefs (active, with suggested actions).
  * Priority emails (priority 1-2 from the last 24h).
  * Tasks due in the next 48h.

The brief is generated by the LLM in one call per user (prompt-cache
friendly: the system prompt is byte-identical across users). The brief
row is replaced via MERGE on (user_email, brief_date).
"""
from __future__ import annotations

# spark_python_task executes this file with sys.path[0] = pipelines/;
# the bundle root (which holds pipelines/ and alex/) must be importable.
import os as _os
import sys as _sys

_ROOT = _os.path.dirname(_os.path.dirname(_os.path.abspath(__file__)))
if _ROOT not in _sys.path:
    _sys.path.insert(0, _ROOT)

import json
import logging
from datetime import datetime

from pyspark.sql import SparkSession
from pyspark.sql.types import (
    ArrayType,
    DateType,
    IntegerType,
    StringType,
    StructField,
    StructType,
)

from pipelines._helpers import with_backoff

log = logging.getLogger("pipelines.morning_brief")

MODEL = "databricks-claude-haiku-4-5"
PROMPT_VERSION = "v2"
PRIORITY_CAP = 2
TASK_HORIZON_HOURS = 48

SYSTEM_PROMPT = """You are the user's morning briefing writer. You receive
their standing orders, priority emails, and due tasks. Write a brief
in 5 sentences or less. The brief is what the user reads first thing
in the morning; it should feel like a real assistant handing them the
day.

Return ONLY a single JSON object, no prose:
{"brief": "<= 700 chars"}"""


def _material_for(user: str) -> dict:
    """Compose the per-user material: standing-order briefs + priority
    emails + tasks-due."""
    spark = SparkSession.builder.getOrCreate()
    sob_sql = """
        SELECT order_id, title, compiled_context, suggested_actions, brief_date
          FROM media.control.standing_order_briefs
         WHERE user_email = :u
           AND consumed = false
           AND brief_date <= current_date()
         ORDER BY brief_date
         LIMIT 5
    """
    emails_sql = """
        SELECT i.email_id, i.priority, i.subject, i.understanding
          FROM media.alex.email_intel i
          JOIN media.alex.emails e ON e.id = i.email_id
         WHERE i.owner_email = :u
           AND i.priority <= :cap
           AND e.received_at >= current_timestamp() - INTERVAL 24 HOURS
         ORDER BY i.priority ASC, e.received_at DESC
         LIMIT 8
    """
    tasks_sql = """
        SELECT id, title, status, priority, due_at
          FROM media.alex.tasks
         WHERE (owner_email = :u OR assignee_email = :u)
           AND status NOT IN ('done','cancelled')
           AND due_at IS NOT NULL
           AND due_at <= :horizon
         ORDER BY due_at ASC
         LIMIT 8
    """
    sob = [r.asDict() for r in spark.sql(sob_sql, args={"u": user}).collect()]
    emails = [r.asDict() for r in
              spark.sql(emails_sql, args={"u": user, "cap": PRIORITY_CAP}).collect()]
    # The task horizon is bound as a value: a parameter marker inside
    # `INTERVAL :h HOURS` is not valid SQL grammar and failed the whole
    # job at compile time.
    from datetime import datetime, timedelta, timezone

    horizon = (datetime.now(timezone.utc) + timedelta(hours=TASK_HORIZON_HOURS)
               ).isoformat()
    tasks = [r.asDict() for r in
             spark.sql(tasks_sql, args={"u": user, "horizon": horizon}).collect()]
    return {"standing_orders": sob, "emails": emails, "tasks": tasks}


def _call_llm(prompt: str) -> str:
    spark = SparkSession.builder.getOrCreate()
    sql = "SELECT ai_query(:m, :p)"
    return str(spark.sql(sql, args={"m": MODEL, "p": prompt}).first()[0])


def _build_for_user(user: str) -> dict:
    material = _material_for(user)
    if not (material["standing_orders"] or material["emails"] or material["tasks"]):
        return {
            "user_email": user,
            "brief_date": datetime.utcnow().date(),
            "brief": "Nothing urgent today. Your standing orders, priority mail, and tasks are all clear.",
            "standing_orders": [],
            "priority_emails": 0,
            "tasks_due": 0,
        }
    user_prompt = (
        f"Material for {user} (UTC {datetime.utcnow().isoformat(timespec='seconds')}):\n\n"
        f"STANDING ORDERS:\n{json.dumps(material['standing_orders'], default=str)[:4000]}\n\n"
        f"PRIORITY EMAILS:\n{json.dumps(material['emails'], default=str)[:4000]}\n\n"
        f"TASKS DUE:\n{json.dumps(material['tasks'], default=str)[:4000]}\n"
    )
    try:
        raw = with_backoff(
            lambda: _call_llm(SYSTEM_PROMPT + "\n\n" + user_prompt),
            attempts=3, base_delay=0.5, max_delay=10.0,
        )
    except Exception as exc:
        log.warning("brief LLM failed for %s: %s", user, exc)
        brief = "Brief unavailable; LLM call failed."
    else:
        try:
            payload = "{" + raw.split("{", 1)[1].rsplit("}", 1)[0] + "}"
            brief = json.loads(payload).get("brief") or ""
        except Exception:
            for line in raw.splitlines():
                line = line.strip()
                if line.startswith("{"):
                    try:
                        brief = json.loads(line).get("brief") or line
                    except Exception:
                        brief = line
                    break
            else:
                brief = (raw or "").strip()[:700]
    return {
        "user_email": user,
        "brief_date": datetime.utcnow().date(),
        "brief": (brief or "")[:2000],
        "standing_orders": [{
            "order_id": s.get("order_id"),
            "title": s.get("title"),
            "summary": (s.get("compiled_context") or "")[:200],
            "suggested_actions": s.get("suggested_actions") or [],
        } for s in material["standing_orders"]],
        "priority_emails": len(material["emails"]),
        "tasks_due": len(material["tasks"]),
    }


def run_brief() -> None:
    spark = SparkSession.builder.getOrCreate()
    users = [r["email"] for r in
             spark.table("media.alex.users").filter("is_active = true").collect()]
    log.info("morning_brief: %d users", len(users))
    rows = [_build_for_user(u) for u in users]
    df = spark.createDataFrame(rows, schema=StructType([
        StructField("user_email", StringType(), False),
        StructField("brief_date", DateType(), False),
        StructField("brief", StringType(), False),
        StructField("standing_orders", ArrayType(StructType([
            StructField("order_id", StringType(), True),
            StructField("title", StringType(), True),
            StructField("summary", StringType(), True),
            StructField("suggested_actions", ArrayType(StructType([
                StructField("action", StringType(), True),
                StructField("capability", StringType(), True),
                StructField("detail", StringType(), True),
            ])), True),
        ])), True),
        StructField("priority_emails", IntegerType(), True),
        StructField("tasks_due", IntegerType(), True),
    ]))
    df.createOrReplaceTempView("briefs_in")
    spark.sql("""
        MERGE INTO media.alex.morning_briefs t
        USING briefs_in s
        ON t.user_email = s.user_email AND t.brief_date = s.brief_date
        WHEN MATCHED THEN UPDATE SET *
        WHEN NOT MATCHED THEN INSERT *
    """)
    log.info("brief done; %d briefs", len(rows))


if __name__ == "__main__":
    run_brief()
